package me.rerere.workspace

import java.io.File
import java.nio.file.Files

class RootfsPatcher {
    fun patch(
        linuxDir: File,
        options: RootfsPatchOptions = RootfsPatchOptions(),
    ) {
        val etcDir = File(linuxDir, "etc")
        if (!etcDir.isDirectory) return

        ensureRootfsDns(etcDir, options.nameservers, options.replaceExistingResolvConf)
        ensureHostsFile(etcDir, options.hostname)
        ensureLocale(etcDir, options.locale)
        ensureGroupNames(etcDir, options.groupIds.ifEmpty { currentSupplementaryGroupIds() })
        ensureTempDirs(linuxDir)
        ensureNodeEnvironment(linuxDir, etcDir)
    }

    private fun ensureNodeEnvironment(linuxDir: File, etcDir: File) {
        // Ensure /usr/local/node mountpoint and /usr/local/bin/{node,npm,npx} symlinks exist
        File(linuxDir, "usr/local/node").mkdirs()
        val usrLocalBin = File(linuxDir, "usr/local/bin").apply { mkdirs() }
        listOf("node", "npm", "npx").forEach { binName ->
            val linkFile = File(usrLocalBin, binName)
            if (!linkFile.exists() && !Files.isSymbolicLink(linkFile.toPath())) {
                runCatching {
                    Files.createSymbolicLink(
                        linkFile.toPath(),
                        java.nio.file.Paths.get("../node/bin/$binName"),
                    )
                }
            }
        }

        // Provision /etc/profile.d/rikka-node.sh so login shells (`bash -l`) keep /usr/local/node/bin in PATH
        // and isolate npm/node caches inside the workspace's private /tmp directory.
        val profileDir = File(etcDir, "profile.d").apply { mkdirs() }
        val nodeProfile = File(profileDir, "rikka-node.sh")
        val desiredProfile = buildString {
            appendLine("# Generated by RikkaHub workspace for shared Node.js runtime")
            appendLine("if [ -d \"/usr/local/node/bin\" ]; then")
            appendLine("  case \":\$PATH:\" in")
            appendLine("    *\":/usr/local/node/bin:\"*) ;;")
            appendLine("    *) export PATH=\"/usr/local/node/bin:\$PATH\" ;;")
            appendLine("  esac")
            appendLine("fi")
            appendLine("export NPM_CONFIG_CACHE=\"\${NPM_CONFIG_CACHE:-/tmp/.npm-cache}\"")
            appendLine("export NODE_COMPILE_CACHE=\"\${NODE_COMPILE_CACHE:-/tmp/.node-compile-cache}\"")
        }
        if (!nodeProfile.isFile || nodeProfile.readText() != desiredProfile) {
            nodeProfile.writeText(desiredProfile)
            nodeProfile.setReadable(true, false)
        }
    }

    private fun ensureRootfsDns(
        etcDir: File,
        preferredNameservers: List<String>,
        replaceExisting: Boolean,
    ) {
        val resolvFile = File(etcDir, "resolv.conf")
        if (!replaceExisting && resolvFile.hasUsableNameserver()) return

        if (Files.isSymbolicLink(resolvFile.toPath())) {
            resolvFile.delete()
        }

        val servers = preferredNameservers
            .map { it.trim() }
            .filter { it.isNotEmpty() }
            .distinct()
            .ifEmpty { DEFAULT_NAMESERVERS }

        val content = buildString {
            appendLine("# Generated by RikkaHub workspace")
            servers.forEach { appendLine("nameserver $it") }
        }
        resolvFile.writeText(content)
    }

    private fun ensureHostsFile(etcDir: File, hostname: String) {
        val hostsFile = File(etcDir, "hosts")
        val existingLines = if (hostsFile.isFile) {
            hostsFile.readLines()
        } else {
            emptyList()
        }

        val normalized = existingLines.map { it.trim() }
        val additions = mutableListOf<String>()
        if (normalized.none { it.startsWith("127.0.0.1") && it.contains("localhost") }) {
            additions += "127.0.0.1 localhost $hostname"
        }
        if (normalized.none { it.startsWith("::1") && it.contains("localhost") }) {
            additions += "::1 localhost ip6-localhost ip6-loopback"
        }
        if (additions.isEmpty() && hostsFile.isFile) return

        val merged = buildString {
            existingLines.forEach { appendLine(it) }
            additions.forEach { appendLine(it) }
        }
        hostsFile.writeText(merged)
    }

    private fun ensureLocale(etcDir: File, locale: String) {
        val localeConf = File(etcDir, "locale.conf")
        val defaultLocale = File(etcDir, "default/locale")
        val content = "LANG=$locale\nLC_ALL=$locale\n"

        if (!localeConf.isFile || localeConf.readText().isBlank()) {
            localeConf.writeText(content)
        }
        defaultLocale.parentFile?.mkdirs()
        if (!defaultLocale.isFile || defaultLocale.readText().isBlank()) {
            defaultLocale.writeText(content)
        }
    }

    private fun ensureGroupNames(etcDir: File, groupIds: Set<Int>) {
        if (groupIds.isEmpty()) return

        val groupFile = File(etcDir, "group")
        val existingLines = if (groupFile.isFile) {
            groupFile.readLines()
        } else {
            emptyList()
        }

        val existingIds = existingLines.mapNotNullTo(mutableSetOf()) { line ->
            val parts = line.split(':')
            parts.getOrNull(2)?.toIntOrNull()
        }
        val existingNames = existingLines.mapNotNullTo(mutableSetOf()) { line ->
            line.substringBefore(':', missingDelimiterValue = "").takeIf { it.isNotEmpty() }
        }

        val missingLines = groupIds
            .filter { it >= 0 && it !in existingIds }
            .sorted()
            .map { gid ->
                val baseName = ANDROID_GROUP_NAMES[gid] ?: "aid_$gid"
                val groupName = if (baseName in existingNames) "${baseName}_$gid" else baseName
                existingNames += groupName
                "$groupName:x:$gid:"
            }

        if (missingLines.isEmpty()) return

        val updated = buildString {
            existingLines.forEach { appendLine(it) }
            missingLines.forEach { appendLine(it) }
        }
        groupFile.writeText(updated)
    }

    private fun ensureTempDirs(linuxDir: File) {
        listOf(
            File(linuxDir, "tmp"),
            File(linuxDir, "var/tmp"),
        ).forEach { dir ->
            dir.mkdirs()
            dir.setReadable(true, false)
            dir.setWritable(true, false)
            dir.setExecutable(true, false)
        }
    }

    private fun currentSupplementaryGroupIds(): Set<Int> {
        val statusFile = File("/proc/self/status")
        if (!statusFile.isFile) return emptySet()

        val groupsLine = statusFile.useLines { lines ->
            lines.firstOrNull { it.startsWith("Groups:") }
        } ?: return emptySet()

        return groupsLine
            .removePrefix("Groups:")
            .trim()
            .split(Regex("\\s+"))
            .mapNotNullTo(linkedSetOf()) { it.toIntOrNull() }
    }

    private fun File.hasUsableNameserver(): Boolean {
        if (!isFile) return false
        return readLines().any { line ->
            val trimmed = line.trim()
            if (!trimmed.startsWith("nameserver")) return@any false
            val server = trimmed.removePrefix("nameserver").trim()
            server.isNotEmpty() && server !in LOOPBACK_NAMESERVERS
        }
    }

    companion object {
        val DEFAULT_NAMESERVERS = listOf("1.1.1.1", "8.8.8.8")
        private val LOOPBACK_NAMESERVERS = setOf("127.0.0.1", "127.0.0.53", "::1")
        private val ANDROID_GROUP_NAMES = mapOf(
            0 to "root",
            3001 to "inet_bt_admin",
            3002 to "inet_bt",
            3003 to "inet",
            3004 to "inet_raw",
            3009 to "readproc",
            9997 to "everybody",
        )
    }
}

data class RootfsPatchOptions(
    val nameservers: List<String> = RootfsPatcher.DEFAULT_NAMESERVERS,
    val replaceExistingResolvConf: Boolean = false,
    val hostname: String = "rikkahub",
    val locale: String = "C.UTF-8",
    val groupIds: Set<Int> = emptySet(),
)
